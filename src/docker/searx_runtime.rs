//! Always-on local SearXNG metasearch (`smith-searxng` on 127.0.0.1:4792).
//!
//! AGPL-3.0 SearXNG image; smith only orchestrates it. JSON API enabled for
//! programmatic search; UI also usable in a browser at the same URL.
//! Loopback bind only — not a public instance.

use super::compose::push_compose_service_labels;
use super::*;
use std::fs;
use std::io::{Read, Write};
use std::net::TcpStream;
use std::path::PathBuf;
use std::time::Duration;

pub const SEARXNG_CONTAINER_NAME: &str = "smith-searxng";
pub const SEARXNG_IMAGE: &str = "docker.io/searxng/searxng:latest";
/// Host loopback port (container listens on 8080).
pub const SEARXNG_PORT: u16 = 4792;

/// Ensure SearXNG is running on loopback :4792 with JSON format enabled.
pub fn ensure_searxng() -> Result<(), String> {
    if std::env::var_os("SMITH_SEARX")
        .map(|v| v == "0" || v.eq_ignore_ascii_case("false") || v.eq_ignore_ascii_case("off"))
        .unwrap_or(false)
    {
        return Err("SearXNG skipped (SMITH_SEARX=0)".to_string());
    }

    check_docker_available()?;

    if searxng_healthy() {
        return Ok(());
    }

    if container_running(SEARXNG_CONTAINER_NAME) {
        // Up but not healthy yet — wait briefly.
        if wait_healthy(45) {
            return Ok(());
        }
        return Err(format!(
            "{SEARXNG_CONTAINER_NAME} is running but /search JSON API not ready on :{SEARXNG_PORT}"
        ));
    }

    let cfg_dir = ensure_searxng_config_dir()?;
    let _ = Command::new("docker")
        .args(["rm", "-f", SEARXNG_CONTAINER_NAME])
        .output();

    let host_cfg = docker_host_path(&cfg_dir);
    let mut args = vec![
        "run".to_string(),
        "-d".to_string(),
        "--restart".to_string(),
        "no".to_string(),
        "--name".to_string(),
        SEARXNG_CONTAINER_NAME.to_string(),
        "-p".to_string(),
        format!("127.0.0.1:{}:8080", SEARXNG_PORT),
        "-v".to_string(),
        format!("{}:/etc/searxng:rw", host_cfg),
        "-e".to_string(),
        format!("SEARXNG_BASE_URL=http://127.0.0.1:{}/", SEARXNG_PORT),
        "-e".to_string(),
        "SEARXNG_LIMITER=false".to_string(),
    ];
    push_compose_service_labels(&mut args, crate::service::LABEL_SERVICES_SEARXNG);
    args.push(SEARXNG_IMAGE.to_string());

    println!(
        "  Starting local search (SearXNG) on http://127.0.0.1:{} …",
        SEARXNG_PORT
    );
    let output = Command::new("docker")
        .args(&args)
        .output()
        .map_err(|e| format!("Failed to start SearXNG: {e}"))?;

    if !output.status.success() {
        let err = String::from_utf8_lossy(&output.stderr);
        let _ = Command::new("docker")
            .args(["rm", "-f", SEARXNG_CONTAINER_NAME])
            .output();
        return Err(format!("Failed to start SearXNG: {}", err.trim()));
    }

    if wait_healthy(90) {
        println!(
            "  SearXNG ready — browser UI + API at http://127.0.0.1:{}",
            SEARXNG_PORT
        );
        Ok(())
    } else {
        let logs = Command::new("docker")
            .args(["logs", "--tail", "40", SEARXNG_CONTAINER_NAME])
            .output()
            .map(|o| {
                format!(
                    "{}{}",
                    String::from_utf8_lossy(&o.stderr),
                    String::from_utf8_lossy(&o.stdout)
                )
            })
            .unwrap_or_default();
        Err(format!(
            "SearXNG started but not ready on :{SEARXNG_PORT}. Logs:\n{}",
            logs.trim()
        ))
    }
}

/// Best-effort stop (uninstall / cleanup).
pub fn stop_searxng() -> Result<(), String> {
    let _ = Command::new("docker")
        .args(["rm", "-f", SEARXNG_CONTAINER_NAME])
        .output();
    Ok(())
}

pub fn searxng_status() -> (bool, bool) {
    (container_running(SEARXNG_CONTAINER_NAME), searxng_healthy())
}

pub fn searxng_base_url() -> String {
    std::env::var("SMITH_SEARX_URL")
        .unwrap_or_else(|_| format!("http://127.0.0.1:{}", SEARXNG_PORT))
}

/// GET /search?q=&format=json — returns raw JSON body.
pub fn searxng_search_json(query: &str) -> Result<String, String> {
    ensure_searxng()?;
    let q = urlencoding_minimal(query);
    let url = format!(
        "{}/search?q={}&format=json&language=en",
        searxng_base_url().trim_end_matches('/'),
        q
    );
    http_get_sync(&url, Duration::from_secs(60))
}

fn ensure_searxng_config_dir() -> Result<PathBuf, String> {
    let dir = crate::config_dir()?.join("searxng");
    fs::create_dir_all(&dir).map_err(|e| format!("searxng config dir: {e}"))?;
    let settings = dir.join("settings.yml");
    if !settings.is_file() {
        let secret = random_hex(32);
        let body = format!(
            r#"# Generated by smith — local metasearch (loopback only).
use_default_settings: true

general:
  instance_name: "smith search"

server:
  secret_key: "{secret}"
  limiter: false
  image_proxy: false
  port: 8080
  bind_address: "0.0.0.0"
  base_url: "http://127.0.0.1:{port}/"

search:
  safe_search: 0
  autocomplete: ""
  default_lang: "en"
  formats:
    - html
    - json
"#,
            secret = secret,
            port = SEARXNG_PORT,
        );
        fs::write(&settings, body).map_err(|e| format!("write settings.yml: {e}"))?;
    } else {
        // Ensure json is listed when missing from an older hand-edited file.
        if let Ok(text) = fs::read_to_string(&settings) {
            if !text.contains("- json") && !text.contains("json") {
                let patched = format!(
                    "{text}\nsearch:\n  safe_search: 0\n  formats:\n    - html\n    - json\n"
                );
                let _ = fs::write(&settings, patched);
            }
        }
    }
    Ok(dir)
}

fn wait_healthy(max_secs: u64) -> bool {
    for attempt in 1..=max_secs {
        if searxng_healthy() {
            return true;
        }
        if !container_running(SEARXNG_CONTAINER_NAME) && attempt > 5 {
            return false;
        }
        std::thread::sleep(Duration::from_secs(1));
    }
    false
}

fn searxng_healthy() -> bool {
    // Prefer JSON format probe — html-only instances would pass a bare TCP check wrongly.
    let url = format!(
        "{}/search?q=smith&format=json",
        searxng_base_url().trim_end_matches('/')
    );
    match http_get_sync(&url, Duration::from_secs(3)) {
        Ok(body) => body.contains("\"results\"") || body.contains("\"query\""),
        Err(_) => false,
    }
}

fn container_running(name: &str) -> bool {
    Command::new("docker")
        .args(["inspect", "-f", "{{.State.Running}}", name])
        .output()
        .map(|o| o.status.success() && String::from_utf8_lossy(&o.stdout).trim() == "true")
        .unwrap_or(false)
}

fn http_get_sync(url: &str, timeout: Duration) -> Result<String, String> {
    // Prefer curl when available (no nested tokio issues).
    if let Ok(out) = Command::new("curl")
        .args([
            "-fsSL",
            "--max-time",
            &timeout.as_secs().max(1).to_string(),
            "-H",
            "Accept: application/json",
            url,
        ])
        .output()
    {
        if out.status.success() {
            return Ok(String::from_utf8_lossy(&out.stdout).to_string());
        }
        let err = String::from_utf8_lossy(&out.stderr);
        if !err.trim().is_empty() {
            // Fall through to raw TCP for simple cases / missing curl.
            let _ = err;
        }
    }

    // Minimal HTTP/1.1 GET for health when curl missing.
    let parsed = parse_http_url(url)?;
    let mut stream = TcpStream::connect((parsed.host.as_str(), parsed.port))
        .map_err(|e| format!("connect {}: {e}", parsed.host))?;
    let _ = stream.set_read_timeout(Some(timeout));
    let _ = stream.set_write_timeout(Some(timeout));
    let req = format!(
        "GET {} HTTP/1.1\r\nHost: {}:{}\r\nAccept: application/json\r\nConnection: close\r\n\r\n",
        parsed.path_query, parsed.host, parsed.port
    );
    stream
        .write_all(req.as_bytes())
        .map_err(|e| format!("write: {e}"))?;
    let mut buf = Vec::new();
    stream
        .read_to_end(&mut buf)
        .map_err(|e| format!("read: {e}"))?;
    let raw = String::from_utf8_lossy(&buf);
    if let Some(idx) = raw.find("\r\n\r\n") {
        Ok(raw[idx + 4..].to_string())
    } else {
        Ok(raw.to_string())
    }
}

struct ParsedUrl {
    host: String,
    port: u16,
    path_query: String,
}

fn parse_http_url(url: &str) -> Result<ParsedUrl, String> {
    let rest = url
        .strip_prefix("http://")
        .ok_or_else(|| format!("only http:// supported: {url}"))?;
    let (hostport, path) = match rest.split_once('/') {
        Some((h, p)) => (h, format!("/{p}")),
        None => (rest, "/".to_string()),
    };
    let (host, port) = if let Some((h, p)) = hostport.split_once(':') {
        (
            h.to_string(),
            p.parse::<u16>().map_err(|_| format!("bad port in {url}"))?,
        )
    } else {
        (hostport.to_string(), 80)
    };
    Ok(ParsedUrl {
        host,
        port,
        path_query: path,
    })
}

fn urlencoding_minimal(s: &str) -> String {
    let mut out = String::new();
    for b in s.as_bytes() {
        match *b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                out.push(char::from(*b));
            }
            b' ' => out.push('+'),
            _ => out.push_str(&format!("%{b:02X}")),
        }
    }
    out
}

fn random_hex(nbytes: usize) -> String {
    use std::collections::hash_map::DefaultHasher;
    use std::hash::{Hash, Hasher};
    use std::time::{SystemTime, UNIX_EPOCH};
    let mut h = DefaultHasher::new();
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0)
        .hash(&mut h);
    std::process::id().hash(&mut h);
    let mut out = String::new();
    let mut seed = h.finish();
    while out.len() < nbytes * 2 {
        seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1);
        out.push_str(&format!("{:016x}", seed));
    }
    out.truncate(nbytes * 2);
    out
}
