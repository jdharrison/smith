//! Docker Compose project identity for smith.
//!
//! Containers are still started via `docker run` (dynamic agents/ports), but every
//! smith resource is labeled with `com.docker.compose.project=smith` so Docker
//! Desktop / `docker compose` treat them as one stack instead of scattered roots.

use super::*;
use std::path::PathBuf;

/// Compose project name shown in Docker Desktop.
pub const COMPOSE_PROJECT: &str = "smith";

/// Named volume for Ollama model weights (must match model_runtime usage).
pub const OLLAMA_VOLUME: &str = "smith-ollama";

fn smith_compose_dir() -> Result<PathBuf, String> {
    crate::config_dir().map(|d| d.join("compose"))
}

/// Host path to the project compose file (created on demand).
pub fn compose_file_path() -> Option<PathBuf> {
    smith_compose_dir().ok().map(|d| d.join("compose.yaml"))
}

/// Ensure `~/.config/smith/compose/compose.yaml` exists for Desktop project grouping.
pub fn ensure_compose_project_file() -> Result<PathBuf, String> {
    let dir = smith_compose_dir()?;
    std::fs::create_dir_all(&dir).map_err(|e| format!("Failed to create compose dir: {}", e))?;
    let path = dir.join("compose.yaml");
    // Keep in sync with OLLAMA_*/BRAIN_* constants in sibling modules.
    let body = format!(
        r#"# Generated by smith CLI — do not hand-edit unless you know why.
# Containers are started by `smith` with matching Compose project labels
# (com.docker.compose.project={project}) so Docker Desktop groups them.
name: {project}

services:
  ollama:
    image: ollama/ollama
    container_name: smith-ollama
    restart: "no"
    ports:
      - "11434:11434"
    volumes:
      - ollama-data:/root/.ollama
    networks:
      - brain-net
      - default
    command: ["serve"]

  brain:
    image: ghcr.io/anomalyco/opencode
    container_name: smith-brain
    restart: "no"
    networks:
      - brain-net
    # Memory bind-mount and entrypoint are applied by `smith chat` / brain start.
    profiles: ["brain"]

  # Named workers (smith-agent-*) and workspace agents (agent_*) are created
  # dynamically by `smith settings agent start …` with the same project labels.
  # One-shot search windows (smith-search-*) use bridge egress then --rm.

networks:
  brain-net:
    name: smith-brain-net
    internal: true

volumes:
  ollama-data:
    name: smith-ollama
"#,
        project = COMPOSE_PROJECT,
    );
    std::fs::write(&path, body).map_err(|e| format!("Failed to write compose.yaml: {}", e))?;
    Ok(path)
}

fn docker_label_path(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}

/// Append Compose project labels to a `docker run` args list (before the image).
pub(crate) fn push_compose_service_labels(args: &mut Vec<String>, service: &str) {
    let _ = ensure_compose_project_file();
    args.push("--label".to_string());
    args.push(format!("com.docker.compose.project={}", COMPOSE_PROJECT));
    args.push("--label".to_string());
    args.push(format!("com.docker.compose.service={}", service));
    args.push("--label".to_string());
    args.push("com.docker.compose.container-number=1".to_string());
    args.push("--label".to_string());
    args.push("com.docker.compose.oneoff=False".to_string());
    if let Some(cfg) = compose_file_path() {
        if let Some(parent) = cfg.parent() {
            args.push("--label".to_string());
            args.push(format!(
                "com.docker.compose.project.working_dir={}",
                docker_label_path(parent)
            ));
        }
        args.push("--label".to_string());
        args.push(format!(
            "com.docker.compose.project.config_files={}",
            docker_label_path(&cfg)
        ));
    }
}

/// Labels for `docker network create`.
pub(crate) fn compose_network_label_args(network_service: &str) -> Vec<String> {
    let _ = ensure_compose_project_file();
    vec![
        "--label".to_string(),
        format!("com.docker.compose.project={}", COMPOSE_PROJECT),
        "--label".to_string(),
        format!("com.docker.compose.network={}", network_service),
    ]
}

/// Ensure the Ollama named volume exists with Compose project labels.
pub(crate) fn ensure_ollama_volume() -> Result<(), String> {
    let inspect = Command::new("docker")
        .args(["volume", "inspect", OLLAMA_VOLUME])
        .output()
        .map_err(|e| format!("Failed to inspect volume: {}", e))?;
    if inspect.status.success() {
        return Ok(());
    }
    let args = [
        "volume",
        "create",
        "--label",
        &format!("com.docker.compose.project={}", COMPOSE_PROJECT),
        "--label",
        "com.docker.compose.volume=ollama-data",
        OLLAMA_VOLUME,
    ];
    let _ = ensure_compose_project_file();
    let create = Command::new("docker")
        .args(args)
        .output()
        .map_err(|e| format!("Failed to create volume: {}", e))?;
    if create.status.success() {
        Ok(())
    } else {
        let err = String::from_utf8_lossy(&create.stderr);
        if err.contains("already exists") {
            Ok(())
        } else {
            Err(format!(
                "Failed to create volume '{}': {}",
                OLLAMA_VOLUME,
                err.trim()
            ))
        }
    }
}

/// Sanitize a dynamic service name for Compose (lowercase, [a-z0-9_-]).
pub fn compose_service_name(raw: &str) -> String {
    let s: String = raw
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '-' || c == '_' {
                c.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect();
    if s.is_empty() {
        "service".to_string()
    } else {
        s
    }
}
